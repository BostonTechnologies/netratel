// Playback consumes captured DOM data only. No server callback, workflow API or graph mutation is used.
export function attach(playerId, contextKey) {
    const root = document.getElementById(playerId);
    if (!root || root.dataset.context !== contextKey) return null;
    const scope = root.dataset.scopeId ? document.getElementById(root.dataset.scopeId) : root.parentElement;
    const panels = Array.from(root.querySelectorAll("[data-trace-panel]"));
    const steps = Array.from(root.querySelectorAll("[data-trace-step]"));
    if (!panels.length) return null;
    const play = root.querySelector('[data-trace-action="play"]');
    const previous = root.querySelector('[data-trace-action="previous"]');
    const next = root.querySelector('[data-trace-action="next"]');
    const position = root.querySelector("[data-trace-position]");
    const speed = root.querySelector("[data-trace-speed]");
    const motion = window.matchMedia("(prefers-reduced-motion: reduce)");
    let index = 0, timer = null, disposed = false, playing = false, visible = true;
    let marked = [];
    root.hidden = false;
    // Owner IDs are generated by the component, not derived from event contents.
    const owner = root.id;
    const style = document.createElement("style");
    style.textContent = `
[data-flow-playback-node="${owner}"] { outline:3px solid var(--mud-palette-info); outline-offset:3px; }
[data-flow-playback-edge="${owner}"] { stroke:var(--mud-palette-info); stroke-width:5; stroke-dasharray:10 7; animation:flowTraceTravel 1s linear infinite; }
[data-flow-playback-paused="${owner}"] { animation-play-state:paused; }
@keyframes flowTraceTravel { to { stroke-dashoffset:-34; } }
@media(prefers-reduced-motion:reduce) { [data-flow-playback-edge="${owner}"] { animation:none; } }
`;
    document.head.append(style);

    const current = () => !disposed && root.isConnected && root.dataset.context === contextKey;
    const cancelTimer = () => { if (timer !== null) window.clearTimeout(timer); timer = null; };
    const clearVisuals = () => {
        for (const element of marked) {
            if (element.getAttribute("data-flow-playback-node") === owner) element.removeAttribute("data-flow-playback-node");
            if (element.getAttribute("data-flow-playback-edge") === owner) element.removeAttribute("data-flow-playback-edge");
            if (element.getAttribute("data-flow-playback-paused") === owner) element.removeAttribute("data-flow-playback-paused");
        }
        marked = [];
    };
    const mark = () => {
        clearVisuals();
        if (!current() || !scope || root.hidden) return;
        const panel = panels[index];
        const nodeId = (panel.dataset.nodeId || "").toLowerCase();
        const targetId = (panel.dataset.nextNodeId || "").toLowerCase();
        const edgeId = (panel.dataset.edgeId || "").toLowerCase();
        for (const node of scope.querySelectorAll(".flow-node[data-node-id]")) {
            if (node.dataset.nodeId.toLowerCase() !== nodeId) continue;
            node.setAttribute("data-flow-playback-node", owner); marked.push(node);
        }
        if (targetId) for (const edge of scope.querySelectorAll("[data-flow-source-node][data-flow-target-node]")) {
            if (edgeId ? (edge.dataset.flowEdgeId || "").toLowerCase() !== edgeId
                : edge.dataset.flowSourceNode.toLowerCase() !== nodeId || edge.dataset.flowTargetNode.toLowerCase() !== targetId) continue;
            edge.setAttribute("data-flow-playback-edge", owner);
            if (!playing || !visible || document.hidden || motion.matches) edge.setAttribute("data-flow-playback-paused", owner);
            marked.push(edge);
        }
    };
    const render = () => {
        if (!current()) return;
        panels.forEach((panel, i) => { panel.hidden = i !== index; });
        steps.forEach((step, i) => {
            if (i === index) step.setAttribute("aria-current", "step"); else step.removeAttribute("aria-current");
        });
        if (play) { play.textContent = playing ? "Pause" : "Play"; play.setAttribute("aria-label", playing ? "Pause playback" : "Play playback"); play.setAttribute("aria-pressed", playing ? "true" : "false"); }
        if (previous) previous.disabled = index === 0;
        if (next) next.disabled = index === panels.length - 1;
        if (position) position.textContent = "Step " + (index + 1) + " of " + panels.length;
        mark();
    };
    const schedule = () => {
        cancelTimer();
        if (!current() || !playing || !visible || document.hidden || root.hidden) return;
        const rate = Number(speed?.value || 1);
        timer = window.setTimeout(() => {
            timer = null;
            if (!current()) return;
            if (index === panels.length - 1) { playing = false; render(); return; }
            index++; render(); schedule();
        }, 1800 / (Number.isFinite(rate) && rate >= 0.5 && rate <= 4 ? rate : 1));
    };
    const seek = (value) => {
        if (!current()) return;
        playing = false; index = Math.max(0, Math.min(panels.length - 1, value));
        render(); schedule();
    };
    const exit = () => {
        playing = false; cancelTimer(); clearVisuals(); root.hidden = true;
        scope?.querySelector('[data-testid="flow-dry-run-toggle"]')?.focus({ preventScroll: true });
    };
    const click = event => {
        const target = event.target instanceof Element ? event.target : null;
        if (!target || !current()) return;
        const step = target.closest("[data-trace-step]");
        if (step && root.contains(step)) { seek(Number(step.dataset.traceStep)); return; }
        const button = target.closest("[data-trace-action]");
        if (!button || !root.contains(button)) return;
        switch (button.dataset.traceAction) {
            case "play": if (index === panels.length - 1 && !playing) index = 0; playing = !playing; render(); schedule(); break;
            case "next": seek(index + 1); break;
            case "previous": seek(index - 1); break;
            case "restart": seek(0); break;
            case "exit": exit(); break;
        }
    };
    const keys = event => {
        if (event.target instanceof Element && event.target.closest("input,select,textarea,pre")) return;
        if (event.key === "ArrowRight") { event.preventDefault(); seek(index + 1); }
        else if (event.key === "ArrowLeft") { event.preventDefault(); seek(index - 1); }
        else if (event.key === "Home") { event.preventDefault(); seek(0); }
        else if (event.key === "End") { event.preventDefault(); seek(panels.length - 1); }
    };
    const canvasClick = event => {
        if (!current() || root.hidden || !(event.target instanceof Element)) return;
        const node = event.target.closest(".flow-node[data-node-id]");
        if (!node || !scope?.contains(node)) return;
        const match = panels.findIndex(panel => panel.dataset.nodeId?.toLowerCase() === node.dataset.nodeId?.toLowerCase());
        if (match >= 0) seek(match);
    };
    const reschedule = () => { render(); schedule(); };
    const observer = new IntersectionObserver(entries => {
        visible = entries.some(entry => entry.isIntersecting); reschedule();
    });
    observer.observe(root);
    const mutations = scope ? new MutationObserver(() => { if (current()) mark(); }) : null;
    // Native canvas replacement may replace node elements; attribute/layout changes do not trigger this observer.
    if (scope) mutations.observe(scope, { childList: true, subtree: true });
    root.addEventListener("click", click);
    root.addEventListener("keydown", keys);
    speed?.addEventListener("change", reschedule);
    scope?.addEventListener("click", canvasClick);
    document.addEventListener("visibilitychange", reschedule);
    motion.addEventListener("change", reschedule);
    render();
    return {
        dispose() {
            if (disposed) return;
            disposed = true; cancelTimer(); observer.disconnect(); mutations?.disconnect(); clearVisuals(); style.remove();
            root.removeEventListener("click", click); root.removeEventListener("keydown", keys);
            speed?.removeEventListener("change", reschedule); scope?.removeEventListener("click", canvasClick);
            document.removeEventListener("visibilitychange", reschedule); motion.removeEventListener("change", reschedule);
        }
    };
}
